#!/usr/bin/env node
/**
 * Build the CANONICAL DesignPanelAI authoring module the runtime calls for the
 * A.T.L.A.S. Call 1 — and the pinned 113d137 reference twin the parity test
 * executes beside it.
 *
 * Owner directive (Trish 2026-08-26): "invoke the real DesignPanelAI creative
 * builder from the server-native ATLAS authoring path without duplicating /
 * reimplementing it. There must be one canonical creative implementation, not
 * two drifting copies."
 *
 * This is the same mechanism as scripts/build-control-prompt.mjs: slice the
 * pure prompt half of `supabase/functions/design-panel-ai-generate/index.ts`
 * (everything above the `serve()` handler), swap only the Deno import header
 * for the three local modules the builders actually use, and bundle with
 * esbuild. NOTHING IS REWRITTEN — the slice is byte-for-byte the vendored
 * source.
 *
 * Two bundles come out of it, both COMMITTED so the runtime and the tests
 * never need esbuild at run time:
 *
 *   runtime/vendor/designpanel-authoring.cjs
 *     from supabase/functions/design-panel-ai-generate/index.ts (the vendored
 *     authority carrying the delimited ATLAS-MODE patch)
 *
 *   tests/fixtures/designpanel-authoring-113d137.cjs
 *     from tests/fixtures/designpanel-ai-generate-113d137.index.ts (pristine
 *     restylepro-os bytes at commit 113d137dbe8813ca3bf70c8d7265ad081ebd4524)
 *
 * Each bundle's first line records the sha256 of the source it was built from;
 * tests/designpanel-vendor-parity.test.mjs recomputes that hash so a stale
 * bundle fails the suite instead of silently serving old creative code.
 *
 * Rebuild:  npx --yes esbuild --version  # any install of esbuild works
 *           node scripts/build-designpanel-authoring.mjs
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, copyFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");

export const SOURCE_HASH_LINE = /^\/\/ designpanel-authoring source sha256: ([0-9a-f]{64})$/m;

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

function pureRegionEnd(source) {
  const index = source.indexOf("\nserve(async (req)");
  if (index < 0) throw new Error("authoring source no longer contains the serve() boundary");
  return index;
}

function buildOne({ sourcePath, outFile, exportNames, reExportShared, esbuild }) {
  const work = mkdtempSync(join(tmpdir(), "dpag-authoring-"));
  try {
    const fns = join(REPO, "supabase", "functions");
    copyFileSync(join(fns, "_shared", "studio-os.ts"), join(work, "studio-os.ts"));
    copyFileSync(join(fns, "_shared", "view-angles-os.ts"), join(work, "view-angles-os.ts"));

    // canonicalizeVehicle + its titleCase helper, without emitRenderEvent's
    // supabase-js import — identical slice to build-control-prompt.mjs.
    const events = readFileSync(join(fns, "_shared", "render-events.ts"), "utf8").split("\n");
    const start = events.findIndex((line) => line.startsWith("export function canonicalizeVehicle("));
    if (start < 0) throw new Error("render-events.ts no longer exports canonicalizeVehicle");
    const tail = events.slice(start).join("\n");
    const titleCaseEnd = tail.indexOf("\nfunction titleCase(");
    const afterTitleCase = tail.slice(titleCaseEnd + 1);
    const titleCaseClose = afterTitleCase.indexOf("\n}\n");
    writeFileSync(
      join(work, "render-events-slice.ts"),
      tail.slice(0, titleCaseEnd + 1) + afterTitleCase.slice(0, titleCaseClose + 3),
    );

    const source = readFileSync(sourcePath, "utf8");
    const sourceHash = sha256(source);
    const pure = source.slice(0, pureRegionEnd(source)).replace(/^import .*?;\s*$/gms, "");
    writeFileSync(
      join(work, "authoring.ts"),
      'import { STUDIO_ENVIRONMENT } from "./studio-os.ts";\n'
      + 'import { getCameraAngle, getAspectRatio, getResolution } from "./view-angles-os.ts";\n'
      + 'import { canonicalizeVehicle } from "./render-events-slice.ts";\n'
      + pure
      + `\nexport { ${exportNames.join(", ")} };\n`
      + (reExportShared ? 'export { STUDIO_ENVIRONMENT } from "./studio-os.ts";\nexport { getCameraAngle } from "./view-angles-os.ts";\n' : ""),
    );

    mkdirSync(dirname(outFile), { recursive: true });
    execFileSync(esbuild, [
      join(work, "authoring.ts"),
      "--bundle", "--format=cjs", "--platform=node", `--outfile=${outFile}`, "--log-level=warning",
      `--banner:js=// GENERATED by scripts/build-designpanel-authoring.mjs — DO NOT EDIT.\n// designpanel-authoring source sha256: ${sourceHash}`,
    ], { stdio: "inherit" });
    return { sourceHash, outFile };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

export function buildDesignPanelAuthoring({ esbuild = process.env.ESBUILD_BIN || "esbuild" } = {}) {
  const vendored = buildOne({
    sourcePath: join(REPO, "supabase", "functions", "design-panel-ai-generate", "index.ts"),
    outFile: join(REPO, "runtime", "vendor", "designpanel-authoring.cjs"),
    exportNames: [
      "buildDesignIQPrompt", "briefWantsPhoto", "splitStyleAndText",
      "buildLogoArchitecture", "truckBedClause",
      "LOGO_REQUIREMENT", "COMMERCIAL_DEPTH", "COMMERCIAL_TRANSLATION",
      "PHOTO_REALISM_LOCK", "COMMERCIAL_PERSONA", "PROFESSIONAL_JUDGMENT",
      "ATLAS_LOGO_AUTHORING_RULE",
    ],
    reExportShared: true,
    esbuild,
  });
  const reference = buildOne({
    sourcePath: join(REPO, "tests", "fixtures", "designpanel-ai-generate-113d137.index.ts"),
    outFile: join(REPO, "tests", "fixtures", "designpanel-authoring-113d137.cjs"),
    // 113d137 predates the ATLAS-MODE hoists, so only what it exports itself.
    exportNames: ["buildDesignIQPrompt", "briefWantsPhoto", "splitStyleAndText"],
    reExportShared: false,
    esbuild,
  });
  return { vendored, reference };
}

if (process.argv[1] && process.argv[1].endsWith("build-designpanel-authoring.mjs")) {
  const built = buildDesignPanelAuthoring();
  console.log(`vendored  ${built.vendored.outFile}\n  source sha256 ${built.vendored.sourceHash}`);
  console.log(`reference ${built.reference.outFile}\n  source sha256 ${built.reference.sourceHash}`);
}
